export interface User {
  id: string;
  name: string;
  balance: number;
}

export interface Bet {
  userId: string;
  number: number;
  amount: number;
}

/**
 * The main data structure for the game
 */
export interface GameState {
  rngResult: number | null; // Random number generated by the wheel
  tableState: Bet[]; // List of all bets on the table
  users: { [key: string]: User };
  isBettingOpen: boolean;
  timeLeft: number; // Synchronized timer (Timer starts at 15 seconds)
}

